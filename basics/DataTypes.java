public class DataTypes {
    public static void main(String[] args){
        //primitive datatypes
        int a =12;
        long b = 2432424234324234L;
        float c=12.43f;
        double d = 2123.2313213;
        char e = 'a';
        boolean g = true;
        var myNum = 12;
        var mybool = true;
        var ch = "rayzen";
        System.out.println(a+"\n"+b+"\n"+c+"\n"+d+"\n"+e+"\n"+g);
        System.out.println(myNum+"\n"+mybool+"\n"+ch);
        //non-primitive datatypes
        String f = "rayzen";
        
    }
}
